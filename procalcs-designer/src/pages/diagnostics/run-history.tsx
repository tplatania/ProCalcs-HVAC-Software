// ─── Status visuals ────────────────────────────────────────────────────

const STATUS_META: Record<ReviewerStatus, { label: string; variant: "secondary" | "default" | "destructive" | "outline"; icon: typeof CircleDashed }> = {
  unset:      { label: "Unset",      variant: "outline",     icon: CircleDashed },
  good:       { label: "Good",       variant: "default",     icon: CheckCircle2 },
  needs_fix:  { label: "Needs fix",  variant: "secondary",   icon: Wrench },
  blocked:    { label: "Blocked",    variant: "destructive", icon: XCircle },
};

const STATUS_OPTIONS: ReviewerStatus[] = ["unset", "good", "needs_fix", "blocked"];

function StatusBadge({ status }: { status: ReviewerStatus }) {
  const m = STATUS_META[status];
  const Icon = m.icon;
  return (
    <Badge variant={m.variant} className="gap-1 px-2">
      <Icon className="w-3 h-3" />
      {m.label}
    </Badge>
  );
}


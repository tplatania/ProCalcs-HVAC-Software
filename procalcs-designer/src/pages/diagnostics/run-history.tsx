function RawPayload({ label, payload }: { label: string; payload: unknown }) {
  const [open, setOpen] = useState(false);
  if (payload == null) return null;
  return (
    <Card>
      <CardHeader
        className="py-3 cursor-pointer select-none"
        onClick={() => setOpen((v) => !v)}
      >
        <CardTitle className="text-xs font-mono flex items-center justify-between">
          <span>{label}</span>
          <span className="text-muted-foreground text-[10px]">
            {open ? "click to hide" : "click to inspect"}
          </span>
        </CardTitle>
      </CardHeader>
      {open && (
        <CardContent className="pt-0">
          <pre className="text-[11px] bg-muted/40 rounded p-3 overflow-x-auto max-h-[400px]">
            {JSON.stringify(payload, null, 2)}
          </pre>
        </CardContent>
      )}
    </Card>
  );
}

function formatDate(iso: string | null): string {
  if (!iso) return "—";
  try {
    const d = new Date(iso);
    return d.toLocaleString(undefined, {
      month: "short",
      day: "numeric",
      hour: "2-digit",
      minute: "2-digit",
    });
  } catch {
    return iso;
  }
}
